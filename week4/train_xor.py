"""Train a 2-2-1 XOR network neuron by neuron and export Verilog weights.

This is supervised perceptron training with engineered intermediate labels:
H1=OR(A,B), H2=NAND(A,B), Y=AND(H1,H2).
It is NOT end-to-end backpropagation. All learned parameters are integers.
"""
from pathlib import Path
import csv
import random

OUT_DIR = Path(__file__).resolve().parent
SAMPLES = [(0, 0), (0, 1), (1, 0), (1, 1)]


def activate(z):
    return int(z > 0)


def predict(weights, bias, inputs):
    return activate(sum(w * x for w, x in zip(weights, inputs)) + bias)


def train_perceptron(inputs, targets, seed, max_epochs=200):
    """Train a binary step neuron using deterministic shuffled SGD."""
    weights = [0, 0]
    bias = 0
    rng = random.Random(seed)
    for epoch in range(1, max_epochs + 1):
        order = list(range(len(inputs)))
        rng.shuffle(order)
        for idx in order:
            error = targets[idx] - predict(weights, bias, inputs[idx])
            weights[0] += error * inputs[idx][0]
            weights[1] += error * inputs[idx][1]
            bias += error
        if all(predict(weights, bias, x) == y
               for x, y in zip(inputs, targets)):
            return weights, bias, epoch
    raise RuntimeError('Training failed to converge')


def verilog_int(value):
    if not -128 <= value <= 127:
        raise ValueError(f'8-bit signed weight overflow: {value}')
    return f"-8'sd{-value}" if value < 0 else f"8'sd{value}"


def main():
    h1_targets = [int(a or b) for a, b in SAMPLES]
    h2_targets = [int(not (a and b)) for a, b in SAMPLES]
    xor_targets = [a ^ b for a, b in SAMPLES]

    w1, b1, e1 = train_perceptron(SAMPLES, h1_targets, seed=42)
    w2, b2, e2 = train_perceptron(SAMPLES, h2_targets, seed=43)

    hidden_inputs = [(predict(w1, b1, x), predict(w2, b2, x))
                     for x in SAMPLES]
    wo, bo, eo = train_perceptron(hidden_inputs, xor_targets, seed=44)

    results = []
    for (a, b), (h1, h2), target in zip(SAMPLES, hidden_inputs, xor_targets):
        y = predict(wo, bo, (h1, h2))
        assert y == target, f'XOR mismatch for A={a}, B={b}'
        results.append((a, b, h1, h2, y, target))

    params = {
        'W_H1_A': w1[0], 'W_H1_B': w1[1], 'B_H1': b1,
        'W_H2_A': w2[0], 'W_H2_B': w2[1], 'B_H2': b2,
        'W_O_H1': wo[0], 'W_O_H2': wo[1], 'B_O': bo,
    }

    header = ['// GENERATED BY train_xor.py — do not edit manually.',
              '// Include this file INSIDE module xor_ann_mac_core.',
              '// Threshold: f(z)=1 if z>0, otherwise 0.']
    for name, value in params.items():
        header.append(f'localparam signed [7:0] {name} = {verilog_int(value)};')
    (OUT_DIR / 'trained_weights.vh').write_text('\n'.join(header) + '\n')

    with (OUT_DIR / 'training_results.csv').open('w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['A', 'B', 'H1', 'H2', 'ANN_Y', 'Expected_XOR'])
        writer.writerows(results)

    print('Training method: supervised neuron-wise perceptron (not backpropagation)')
    print(f'H1 OR   weights={w1}, bias={b1}, epochs={e1}')
    print(f'H2 NAND weights={w2}, bias={b2}, epochs={e2}')
    print(f'Y AND   weights={wo}, bias={bo}, epochs={eo}')
    print('\nA B | H1 H2 | Y Expected')
    for row in results:
        print(f'{row[0]} {row[1]} |  {row[2]}  {row[3]} | {row[4]}    {row[5]}')
    print('\nExported trained_weights.vh and training_results.csv')


if __name__ == '__main__':
    main()